package blockbox

/** The built-in 5x7 face. Each atlas column belongs to the character above it. Edit # for an ink
  * pixel and . for empty space; no binary masks or conversions are needed. Pixels are decoded once
  * and reused by the text mesh cache.
  */
object PixelFont:
  val width = 5
  val height = 7
  val advance = 6
  final case class Glyph(pixels: Vector[(Int, Int)])

  private def group(
      characters: String,
      artwork: String,
      glyphWidth: Int = width
  ): Map[Char, Glyph] =
    val rows = artwork.linesIterator
      .map(_.trim)
      .filter(_.nonEmpty)
      .map(_.split("\\s+").toVector)
      .toVector
    require(
      rows.length == height && rows.forall(_.length == characters.length),
      "Invalid font atlas dimensions"
    )
    require(
      rows.flatten.forall(row => row.length == glyphWidth && row.forall(c => c == '#' || c == '.')),
      "Invalid font atlas pixels"
    )
    characters.zipWithIndex.map { (ch, column) =>
      ch -> Glyph((for y <- 0 until height; x <- 0 until glyphWidth if rows(y)(column)(x) == '#'
      yield (x, y)).toVector)
    }.toMap

